const LANGS = Object.keys(I18N);

function loadLang() {
  try {
    const saved = localStorage.getItem("lang");
    if (LANGS.includes(saved)) return saved;
  } catch {}
  return "es";
}

let lang = loadLang();

function t(key, params = {}) {
  const s = I18N[lang][key] ?? I18N.es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

// Server errors: {code, params, message}. Unknown codes fall back to the
// server's (English) message.
function tErr(err) {
  if (!err) return "";
  if (typeof err === "string") return err; // state saved by an older version
  const key = `err.${err.code}`;
  return err.code && key in I18N[lang] ? t(key, err.params || {}) : err.message;
}

// root: the document, or a freshly cloned <template> fragment.
function applyStaticI18n(root = document) {
  if (root === document) document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-alt]")) el.alt = t(el.dataset.i18nAlt);
  for (const b of root.querySelectorAll("[data-lang]")) b.setAttribute("aria-pressed", b.dataset.lang === lang);
}

function setLang(next) {
  if (!LANGS.includes(next)) return;
  lang = next;
  try {
    localStorage.setItem("lang", lang);
  } catch {}
  applyStaticI18n();
}
